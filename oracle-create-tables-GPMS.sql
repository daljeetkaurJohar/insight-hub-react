-- ─────────────────────────────────────────────────────────────
--  Insight Hub - tables for the GPMS Oracle database
--  Naming: T_IH_<NAME>   (T_ = table, IH = Insight Hub)
--  Needs Oracle 12c or newer (uses IDENTITY columns).
--
--  How to run in Oracle SQL Developer:
--    1. Connect as the GPMS schema user (the user that should own the tables)
--    2. Paste this whole file into the worksheet
--    3. Press F5  (Run Script - NOT Ctrl+Enter)
--  If a table already exists you will see ORA-00955 for it - that is fine.
-- ─────────────────────────────────────────────────────────────

-- 1. People who log in
CREATE TABLE T_IH_USERS (
    ID           NUMBER GENERATED BY DEFAULT AS IDENTITY,
    EXTERNAL_ID  VARCHAR2(200 CHAR) NOT NULL,      -- employee ID / login ID
    NAME         VARCHAR2(200 CHAR) NOT NULL,
    EMAIL        VARCHAR2(320 CHAR),
    CREATED_AT   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_T_IH_USERS PRIMARY KEY (ID),
    CONSTRAINT UQ_T_IH_USERS_EXT_ID UNIQUE (EXTERNAL_ID)
);

-- 2. Knowledge entries
CREATE TABLE T_IH_ENTRIES (
    ID              NUMBER GENERATED BY DEFAULT AS IDENTITY,
    TITLE           VARCHAR2(300 CHAR) NOT NULL,
    CHANNEL         VARCHAR2(100 CHAR) NOT NULL,
    SUB_TYPE        VARCHAR2(200 CHAR),
    NATURE          VARCHAR2(20 CHAR)  NOT NULL,   -- Observation | Idea | Problem
    SOURCE          VARCHAR2(300 CHAR),
    LOCATION        VARCHAR2(300 CHAR),
    ENTRY_DATE      DATE NOT NULL,
    DESCRIPTION     CLOB NOT NULL,
    CONTRIBUTOR_ID  NUMBER NOT NULL,
    CREATED_AT      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_T_IH_ENTRIES PRIMARY KEY (ID),
    CONSTRAINT FK_T_IH_ENTRIES_USERS FOREIGN KEY (CONTRIBUTOR_ID) REFERENCES T_IH_USERS (ID)
);

CREATE INDEX IX_T_IH_ENTRIES_DATE ON T_IH_ENTRIES (ENTRY_DATE);

-- 3. Images attached to entries (the image files are saved in backend\uploads)
CREATE TABLE T_IH_ENTRY_IMAGES (
    ID             NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ENTRY_ID       NUMBER NOT NULL,
    FILE_NAME      VARCHAR2(255 CHAR) NOT NULL,
    ORIGINAL_NAME  VARCHAR2(255 CHAR),
    CREATED_AT     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_T_IH_ENTRY_IMAGES PRIMARY KEY (ID),
    CONSTRAINT FK_T_IH_IMAGES_ENTRIES FOREIGN KEY (ENTRY_ID) REFERENCES T_IH_ENTRIES (ID) ON DELETE CASCADE
);

-- 4. Comments
CREATE TABLE T_IH_COMMENTS (
    ID          NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ENTRY_ID    NUMBER NOT NULL,
    USER_ID     NUMBER NOT NULL,
    BODY        CLOB NOT NULL,
    CREATED_AT  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_T_IH_COMMENTS PRIMARY KEY (ID),
    CONSTRAINT FK_T_IH_COMMENTS_ENTRIES FOREIGN KEY (ENTRY_ID) REFERENCES T_IH_ENTRIES (ID) ON DELETE CASCADE,
    CONSTRAINT FK_T_IH_COMMENTS_USERS FOREIGN KEY (USER_ID) REFERENCES T_IH_USERS (ID)
);

-- 5. Star ratings, one per person per entry
CREATE TABLE T_IH_RATINGS (
    ENTRY_ID    NUMBER NOT NULL,
    USER_ID     NUMBER NOT NULL,
    STARS       NUMBER(1) NOT NULL,
    UPDATED_AT  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_T_IH_RATINGS PRIMARY KEY (ENTRY_ID, USER_ID),
    CONSTRAINT CK_T_IH_RATINGS_STARS CHECK (STARS BETWEEN 1 AND 5),
    CONSTRAINT FK_T_IH_RATINGS_ENTRIES FOREIGN KEY (ENTRY_ID) REFERENCES T_IH_ENTRIES (ID) ON DELETE CASCADE,
    CONSTRAINT FK_T_IH_RATINGS_USERS FOREIGN KEY (USER_ID) REFERENCES T_IH_USERS (ID)
);

